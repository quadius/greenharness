/**
 * Helpers for the two DSH hooks that carry per-step routing, plus the model-switch notice that
 * per-step routing provokes.
 *
 * DSH keeps the last logged request header and seeds the next model call from it, so a route
 * must be applied on every call, not only where the tier changes. The `agent/request` waterfall
 * is where a plugin replaces the call configuration; `agent/pre-step` is where it can edit the
 * messages admitted to a step.
 */

/** The notice text DSH appends when the assembled selection differs from the last request. */
const NOTICE_RE = /\[model changed: assistant turns above this point were generated by (.+?); the session continues with (.+?)\]/

/**
 * Replace provider, model and reasoning effort in one model-call configuration. Every other
 * control is kept. The inherited effort is always dropped first, so a route without an effort
 * does not keep the previous tier's effort.
 *
 * @param {Record<string, any>} config - the configuration DSH would use (not mutated).
 * @param {{ provider: string, model: string, reasoningEffort?: string }} route - the tier route.
 * @returns {Record<string, any>} a new configuration.
 */
export function applyRoute(config, route) {
  const { reasoningEffort: _inheritedEffort, ...controls } = config
  return {
    ...controls,
    provider: route.provider,
    model: route.model,
    ...(route.reasoningEffort === undefined ? {} : { reasoningEffort: route.reasoningEffort }),
  }
}

/**
 * Read the two endpoints out of one model-switch notice.
 * @param {{ content?: unknown, source?: { kind?: string } }} message - one admitted message.
 * @returns {{ from: string, to: string } | undefined} the parsed endpoints, when this is a notice.
 */
export function parseModelNotice(message) {
  if (message?.source?.kind !== 'model-selection') return undefined
  const content = message.content
  const text = typeof content === 'string'
    ? content
    : Array.isArray(content)
      ? content.map(block => (block && typeof block === 'object' && 'text' in block ? String(block.text) : '')).join('')
      : ''
  const match = NOTICE_RE.exec(text)
  return match === null ? undefined : { from: match[1].trim(), to: match[2].trim() }
}

/**
 * Drop only the model-switch notices that GreenHarness's own routing caused, and report the rest.
 *
 * DSH adds a notice whenever the entry point's default selection differs from the last logged
 * request, which per-step routing makes differ on purpose. A notice is treated as ours when the
 * model it says generated the earlier turns is the route this plugin applied to the previous
 * call; a notice about any other model is a real user switch and is kept.
 *
 * @template {{ source?: { kind?: string } | undefined, content?: unknown }} T
 * @param {ReadonlyArray<T>} messages - the messages admitted to a step.
 * @param {{
 *   policy?: 'tier' | 'all' | 'none',
 *   applied?: { provider?: string, model?: string } | undefined,
 *   isTierModel?: (label: string) => boolean,
 * }} [options]
 * @returns {{ messages: T[], stripped: number, kept: number }}
 */
export function stripModelNotices(messages, options = {}) {
  const policy = options.policy ?? 'tier'
  if (policy === 'none') return { messages: [...messages], stripped: 0, kept: 0 }
  const applied = options.applied
  const isTierModel = options.isTierModel ?? (() => false)
  const ours = (notice) => {
    if (policy === 'all') return true
    if (applied === undefined) return isTierModel(notice.from)
    const bare = String(applied.model ?? '')
    const qualified = applied.provider ? `${applied.provider}/${bare}` : bare
    return notice.from === bare || notice.from === qualified || isTierModel(notice.from)
  }

  const kept = []
  let stripped = 0
  let keptNotices = 0
  for (const message of messages) {
    const notice = parseModelNotice(message)
    if (notice === undefined) {
      kept.push(message)
      continue
    }
    if (ours(notice)) {
      stripped += 1
      continue
    }
    keptNotices += 1
    kept.push(message)
  }
  return { messages: kept, stripped, kept: keptNotices }
}
