import { test } from 'node:test'
import assert from 'node:assert/strict'
import { applyRoute, parseModelNotice, stripModelNotices } from '../src/core/route.mjs'

test('applyRoute replaces provider, model and effort and keeps every other control', () => {
  const config = { provider: 'p', model: 'm', reasoningEffort: 'high', maxTokens: 512, stop: ['x'] }
  const routed = applyRoute(config, { provider: 'nemo-small', model: 'bolt-e4b', reasoningEffort: 'off' })
  assert.deepEqual(routed, { provider: 'nemo-small', model: 'bolt-e4b', reasoningEffort: 'off', maxTokens: 512, stop: ['x'] })
  assert.equal(config.provider, 'p', 'the input is not mutated')
})

test('a route without an effort drops the inherited effort', () => {
  const routed = applyRoute({ provider: 'p', model: 'm', reasoningEffort: 'high' }, { provider: 'nemo-small', model: 'bolt-e4b' })
  assert.deepEqual(routed, { provider: 'nemo-small', model: 'bolt-e4b' })
  assert.equal('reasoningEffort' in routed, false)
})

const notice = (from, to) => ({
  role: 'user',
  source: { kind: 'model-selection' },
  content: [{ type: 'text', text: `[model changed: assistant turns above this point were generated by ${from}; the session continues with ${to}]` }],
})

test('a switch notice is parsed into its two endpoints', () => {
  assert.deepEqual(parseModelNotice(notice('nemo/bolt-e4b', 'deepseek/flash')), { from: 'nemo/bolt-e4b', to: 'deepseek/flash' })
  assert.equal(parseModelNotice({ role: 'user', source: { kind: 'user' }, content: 'hi' }), undefined)
  assert.equal(parseModelNotice({ role: 'user', source: { kind: 'model-selection' }, content: 'something else' }), undefined)
})

test('only the notices caused by our own route are removed', () => {
  const ours = notice('nemo/bolt-e4b', 'deepseek/flash')
  const foreign = notice('someone/else', 'deepseek/flash')
  const other = { role: 'tool', source: { kind: 'tool' }, content: [] }
  const filtered = stripModelNotices([ours, foreign, other], {
    policy: 'tier',
    applied: { provider: 'nemo', model: 'bolt-e4b' },
  })
  assert.deepEqual(filtered.messages, [foreign, other])
  assert.equal(filtered.stripped, 1)
  assert.equal(filtered.kept, 1)
})

test('a notice whose earlier model is a configured tier is treated as ours', () => {
  const filtered = stripModelNotices([notice('bolt-e4b', 'deepseek/flash')], {
    policy: 'tier',
    applied: undefined,
    isTierModel: label => label === 'bolt-e4b',
  })
  assert.equal(filtered.stripped, 1)
})

test('policy none keeps every notice, policy all removes them', () => {
  const messages = [notice('nemo/bolt-e4b', 'deepseek/flash'), notice('someone/else', 'deepseek/flash')]
  assert.equal(stripModelNotices(messages, { policy: 'none' }).stripped, 0)
  assert.equal(stripModelNotices(messages, { policy: 'all' }).stripped, 2)
})
