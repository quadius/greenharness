import { test } from 'node:test'
import assert from 'node:assert/strict'
import { mkdtemp, readdir, readFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { apply, Config, inject, name } from '../src/index.mjs'

const SMALL = { provider: 'p', model: 'small-model', reasoningEffort: '' }
const LARGE = { provider: 'p', model: 'large-model', reasoningEffort: 'high' }
const TEST_FAIL = [
  'not ok 2 - subtracts',
  "  error: 'Expected values to be strictly equal:'",
  '  expected: 2',
  '  actual: 3',
  '# fail 1',
].join('\n')

/** A Cordis-shaped context: records hooks, drains effects, and collects command definitions. */
function fakeCtx({ llm } = {}) {
  const handlers = new Map()
  const commands = []
  const disposers = []
  const ctx = {
    logger: { warn() {} },
    commands: { register(definition) { commands.push(definition); return () => {} } },
    llm,
    on(event, handler) {
      const list = handlers.get(event) ?? []
      list.push(handler)
      handlers.set(event, list)
      return () => {}
    },
    get() { return undefined },
    effect(effect) {
      const result = effect()
      if (result !== undefined && typeof result[Symbol.iterator] === 'function' && typeof result.next === 'function') {
        for (const _ of result) { /* the body already ran; disposers are ignored here */ }
      }
      disposers.push(result)
    },
  }
  return { ctx, handlers, commands, disposers }
}

function fakeAgent(id, cwd) {
  const hooks = new Map()
  return {
    id,
    session: { header: { id, cwd } },
    ctx: {
      on(event, handler, options) {
        const list = hooks.get(event) ?? []
        list.push({ handler, options })
        hooks.set(event, list)
        return () => {}
      },
    },
    hooks,
  }
}

function boot({ config = {}, llm } = {}) {
  const fake = fakeCtx({ llm })
  apply(fake.ctx, { tiers: { small: { ...SMALL }, large: { ...LARGE } }, ...config })
  assert.ok(fake.commands.length === 1, 'the /greenharness command is registered')
  return { ...fake, boot: fake }
}

test('the plugin mounts the hooks it needs and injects commands and llm', () => {
  assert.equal(name, 'greenharness')
  assert.deepEqual(inject, ['commands', 'llm'])
  assert.ok(Config !== undefined, 'the config schema is exported')
  const { handlers } = boot()
  for (const event of ['agent/created', 'agent/disposed', 'agent/request', 'tools/pre-execute', 'tools/post-execute', 'session/event']) {
    assert.ok((handlers.get(event) ?? []).length > 0, `${event} is mounted`)
  }
})

test('a routed call reaches the model waterfall as the large tier', async () => {
  const { handlers } = boot()
  const agent = fakeAgent('s1', '/tmp')
  await handlers.get('agent/created')[0]({ agent })
  const proposed = { provider: 'p', model: 'small-model', maxTokens: 256 }
  const routed = await handlers.get('agent/request')[0]({ agent }, async () => proposed)
  assert.equal(routed.provider, 'p')
  assert.equal(routed.model, 'small-model', 'the first call of a session starts on the small tier')
  assert.equal(routed.maxTokens, 256, 'other controls survive the rewrite')
})

test('a model-switch notice from our own route is removed; a foreign one is kept', async () => {
  const { handlers, commands } = boot()
  const agent = fakeAgent('s2', '/tmp')
  await handlers.get('agent/created')[0]({ agent })
  await handlers.get('agent/request')[0]({ agent }, async () => ({ provider: 'p', model: 'small-model' }))

  const notice = (from) => ({
    role: 'user',
    source: { kind: 'model-selection' },
    content: [{ type: 'text', text: `[model changed: assistant turns above this point were generated by ${from}; the session continues with p/small-model]` }],
  })
  const user = { role: 'user', source: { kind: 'user' }, content: 'fix the tests' }
  const preStep = agent.hooks.get('agent/pre-step')[0].handler
  const admitted = await preStep({}, async () => ({ kind: 'enter', messages: [user, notice('p/small-model')] }))
  assert.deepEqual(admitted.messages, [user], 'the notice our routing caused is stripped')

  const kept = await preStep({}, async () => ({ kind: 'enter', messages: [user, notice('someone/else')] }))
  assert.equal(kept.messages.length, 2, 'a switch to a model we do not route is real information')

  const doctor = await commands[0].handler({ rawInput: 'doctor', agent })
  assert.match(doctor.text, /notice\(s\) were kept/)
})

test('a noisy bash result is distilled and its full text is saved inside the workspace', async () => {
  const cwd = await mkdtemp(join(tmpdir(), 'greenharness-plugin-'))
  const { handlers } = boot()
  const agent = fakeAgent('s3', cwd)
  await handlers.get('agent/created')[0]({ agent })
  const noise = Array.from({ length: 120 }, (_, i) => `✓ case ${i} (1ms)`).join('\n')
  const raw = `${noise}\n${TEST_FAIL}`
  const exec = { agent, name: 'bash', arguments: { command: 'npm test' }, callId: 'call-1' }
  const result = { isError: false, value: { exitCode: 1 }, content: [{ type: 'text', text: raw }] }
  const decision = await handlers.get('tools/post-execute')[0](exec, result, async () => ({ kind: 'accept' }))
  assert.equal(decision.kind, 'accept')
  const text = decision.content[0].text
  assert.ok(text.length < raw.length / 2)
  assert.match(text, /not ok 2 - subtracts/)
  const outputs = await readdir(join(cwd, '.greenharness', 'outputs'))
  assert.equal(outputs.length, 1)
  assert.match(text, new RegExp(outputs[0].replace(/[.*+?^${}()|[\]\\]/g, '\\$&')))
  assert.equal(await readFile(join(cwd, '.greenharness', 'outputs', outputs[0]), 'utf8'), raw)
})

test('the loop breaker denies a third identical failure through the real hook', async () => {
  const cwd = await mkdtemp(join(tmpdir(), 'greenharness-plugin-'))
  const { handlers } = boot()
  const agent = fakeAgent('s4', cwd)
  await handlers.get('agent/created')[0]({ agent })
  const exec = { agent, name: 'bash', arguments: { command: 'node --test' }, callId: 'c' }
  const result = { isError: false, value: { exitCode: 1 }, content: [{ type: 'text', text: TEST_FAIL }] }
  for (let i = 0; i < 3; i += 1) {
    await handlers.get('tools/post-execute')[0](exec, result, async () => ({ kind: 'accept' }))
  }
  const denied = await handlers.get('tools/pre-execute')[0](exec, async () => ({ kind: 'allow' }))
  assert.equal(denied.kind, 'deny')
  assert.match(denied.reason, /failed 3 times in a row/)
})

test('a disposed agent releases its session state', async () => {
  const { handlers, commands } = boot()
  const agent = fakeAgent('s5', '/tmp')
  await handlers.get('agent/created')[0]({ agent })
  await handlers.get('agent/request')[0]({ agent }, async () => ({ provider: 'p', model: 'small-model' }))
  assert.match((await commands[0].handler({ rawInput: 'doctor', agent })).text, /Sessions holding state: 1/)
  await handlers.get('agent/disposed')[0]({ agent })
  assert.match((await commands[0].handler({ rawInput: 'doctor', agent })).text, /Sessions holding state: 0/)
})

test('model-assisted triage classifies through llm.stream', async () => {
  const calls = []
  const llm = {
    async *stream(options) {
      calls.push(options)
      yield { type: 'text-delta', index: 0, text: 'large' }
      yield { type: 'finish', reason: { kind: 'stop' } }
    },
  }
  const { handlers, commands } = boot({
    config: { triage: { mode: 'model', model: { provider: 'p', model: 'judge' } } },
    llm,
  })
  const agent = fakeAgent('s6', '/tmp')
  await handlers.get('agent/created')[0]({ agent })
  const preStep = agent.hooks.get('agent/pre-step')[0].handler
  await preStep({}, async () => ({ kind: 'enter', messages: [{ role: 'user', source: { kind: 'user' }, content: 'build a 3D horse' }] }))
  assert.equal(calls.length, 1)
  assert.equal(calls[0].provider, 'p')
  assert.equal(calls[0].model, 'judge')
  assert.equal(calls[0].maxTokens, 8)
  const routed = await handlers.get('agent/request')[0]({ agent }, async () => ({ provider: 'p', model: 'small-model' }))
  assert.equal(routed.model, 'large-model', 'a "large" verdict routes the turn to the large tier')
  assert.match((await commands[0].handler({ rawInput: 'doctor', agent })).text, /Triage: model/)
})

test('a failed triage model call falls back to the heuristic instead of failing the run', async () => {
  const llm = {
    async *stream() {
      yield { type: 'finish', reason: { kind: 'error', failure: { message: 'boom', code: 'X' } } }
    },
  }
  const { handlers } = boot({
    config: { triage: { mode: 'model', model: { provider: 'p', model: 'judge' } } },
    llm,
  })
  const agent = fakeAgent('s7', '/tmp')
  await handlers.get('agent/created')[0]({ agent })
  const preStep = agent.hooks.get('agent/pre-step')[0].handler
  const decision = await preStep({}, async () => ({ kind: 'enter', messages: [{ role: 'user', source: { kind: 'user' }, content: 'hi there' }] }))
  assert.equal(decision.messages.length, 1, 'the step still runs')
  const routed = await handlers.get('agent/request')[0]({ agent }, async () => ({ provider: 'p', model: 'small-model' }))
  assert.equal(routed.model, 'small-model', 'the heuristic keeps a greeting on the small tier')
})
